"""Verify preserved evidence and maintained docs; stdlib only, no extraction."""
from __future__ import annotations

import argparse
import csv
import hashlib
from html.parser import HTMLParser
import io
import json
from pathlib import Path, PurePosixPath
import re
from urllib.parse import unquote, urlsplit
import zipfile

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = Path('evidence/manifest.json')
COVERAGE = Path('docs/en/evidence-coverage.md')


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def safe_path(name: str) -> bool:
    path = PurePosixPath(name.replace('\\', '/'))
    return bool(name) and not path.is_absolute() and '..' not in path.parts and ':' not in name


def verify_evidence(root: Path, manifest: dict) -> list[str]:
    errors = []
    for entry in manifest['files']:
        name = entry['path']
        if not safe_path(name):
            errors.append(f'Unsafe evidence path: {name}')
            continue
        path = root / name
        if not path.is_file():
            errors.append(f'Missing original file: {name}')
            continue
        raw = path.read_bytes()
        if len(raw) != entry['bytes'] or sha256(raw) != entry['sha256']:
            errors.append(f'Original file changed: {name}')
            continue
        if 'members' not in entry:
            continue
        try:
            with zipfile.ZipFile(io.BytesIO(raw)) as archive:
                infos = archive.infolist()
                names = [info.filename for info in infos]
                if len(names) != len(set(names)):
                    errors.append(f'Duplicate ZIP member: {name}')
                actual = []
                for info in infos:
                    if not safe_path(info.filename):
                        errors.append(f'Unsafe ZIP member: {name}: {info.filename}')
                        continue
                    # Reading each member also validates its CRC; never extract.
                    content = archive.read(info)
                    actual.append({'path': info.filename, 'bytes': info.file_size,
                                   'crc32': f'{info.CRC:08x}', 'sha256': sha256(content)})
                if actual != entry['members']:
                    errors.append(f'ZIP inventory changed: {name}')
        except (zipfile.BadZipFile, OSError, RuntimeError, NotImplementedError) as exc:
            errors.append(f'Invalid ZIP {name}: {exc}')
    return errors


def verify_markdown(root: Path) -> list[str]:
    errors = []
    docs = [root / 'README.md', root / 'CONTRIBUTING.md']
    docs += [root / name for name in ('README.zh-CN.md', 'CHANGELOG.md') if (root / name).is_file()]
    docs += sorted((root / 'docs/en').glob('*.md'))
    for path in docs:
        if not path.is_file():
            errors.append(f'Missing maintained document: {path.relative_to(root)}')
            continue
        text = path.read_text(encoding='utf-8')
        if not text.startswith('# '):
            errors.append(f'Missing document title: {path.relative_to(root)}')
        for target in re.findall(r'\[[^\]]*\]\(([^\s]+)\)', text):
            url = urlsplit(target.strip('<>'))
            if url.scheme or url.netloc or not url.path:
                continue
            destination = (path.parent / unquote(url.path)).resolve()
            if not destination.is_relative_to(root.resolve()):
                errors.append(f'Link escapes repository: {path.relative_to(root)} -> {target}')
            elif not destination.exists():
                errors.append(f'Broken local link: {path.relative_to(root)} -> {target}')
    return errors


class References(HTMLParser):
    def __init__(self):
        super().__init__()
        self.links = set()

    def handle_starttag(self, tag, attrs):
        for key, value in attrs:
            if key in {'href', 'src'} and value:
                url = urlsplit(value)
                if not url.scheme and not url.netloc and url.path:
                    self.links.add(unquote(url.path).replace('\\', '/'))


def coverage_text(root: Path, manifest: dict) -> str:
    members = {}
    for entry in manifest['files']:
        for member in entry.get('members', []):
            members.setdefault(member['path'], []).append(entry['path'])
    lines = ['# Historical reference coverage', '',
             '[Repository home](../../README.md) · [Evidence guide](evidence-guide.md)', '',
             'Generated by `python tools/verify_repository.py --write-coverage`.', '',
             'This audits local href/src targets in the three preserved HTML reports. It does not '
             'audit every filename mentioned in prose or CSV inventories. External URLs and embedded '
             'data images are excluded. ZIP matches require an exact member path, not a matching basename.', '',
             'A missing reference is a publication gap, not proof that an experiment never occurred. '
             'An archive-only reference is not a directly navigable GitHub file.', '']
    counts = {'repository file': 0, 'archive member': 0, 'not published': 0}
    for source in sorted(entry['path'] for entry in manifest['files'] if entry['path'].endswith('.html')):
        parser = References()
        parser.feed((root / source).read_text(encoding='utf-8'))
        lines.extend([f'## `{source}`', '', '| Historical target | Coverage | Package / note |',
                      '| --- | --- | --- |'])
        for target in sorted(parser.links):
            resolved = (root / source).parent / target
            if safe_path(target) and resolved.is_file():
                status, note = 'repository file', 'Available at its original path'
            elif target in members:
                status, note = 'archive member', '; '.join(f'`{name}`' for name in members[target])
            else:
                status, note = 'not published', 'No file or exact ZIP-member match in this snapshot'
            counts[status] += 1
            lines.append(f'| `{target}` | {status} | {note} |')
        lines.append('')
    lines.extend(['## Totals', '', '| Coverage | References |', '| --- | ---: |'])
    lines.extend(f'| {key} | {value} |' for key, value in counts.items())
    return '\n'.join(lines) + '\n'


def verify_csvs(root: Path, manifest: dict) -> list[str]:
    errors = []
    for entry in manifest['files']:
        if not entry['path'].endswith('.csv'):
            continue
        with (root / entry['path']).open(encoding='utf-8-sig', newline='') as stream:
            reader = csv.DictReader(stream)
            if reader.fieldnames not in (['RelativePath', 'Bytes', 'SHA256'], ['File', 'Bytes', 'SHA256']):
                errors.append(f'Unexpected CSV header: {entry["path"]}')
                continue
            for number, row in enumerate(reader, 2):
                if (None in row or not (row.get('Bytes') or '').isdigit()
                        or not re.fullmatch(r'[0-9A-Fa-f]{64}', row.get('SHA256') or '')
                        or not row.get(reader.fieldnames[0])):
                    errors.append(f'Invalid inventory row: {entry["path"]}:{number}')
    return errors


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write-coverage', action='store_true', help='Regenerate the coverage document only')
    args = parser.parse_args()
    manifest = json.loads((ROOT / MANIFEST).read_text(encoding='utf-8'))
    errors = verify_evidence(ROOT, manifest)
    # Do not generate apparently valid coverage from altered/missing evidence.
    if not errors:
        expected = coverage_text(ROOT, manifest)
        if args.write_coverage:
            (ROOT / COVERAGE).write_text(expected, encoding='utf-8')
        if not (ROOT / COVERAGE).is_file() or (ROOT / COVERAGE).read_text(encoding='utf-8') != expected:
            errors.append('Evidence coverage is missing or stale; run with --write-coverage')
        errors.extend(verify_csvs(ROOT, manifest))
    errors.extend(verify_markdown(ROOT))
    if errors:
        for error in errors:
            print('ERROR:', error)
        return 1
    members = sum(len(entry.get('members', [])) for entry in manifest['files'])
    print(f'OK: {len(manifest["files"])} original files, {members} ZIP members, CSV inventories, local Markdown links, and coverage report')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
